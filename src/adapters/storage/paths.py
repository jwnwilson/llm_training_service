"""Canonical S3 key constructors for model and dataset artefacts.

All code that writes or reads a model from storage must go through these
helpers so that the key format is consistent across export, activation,
and inference pod injection.
"""

from __future__ import annotations


def standalone_model_key(model_id: str, model_name: str = "model") -> str:
    """Return the S3 key for a named / standalone model export.

    Format: model/{model_id}/{model_name}.gguf
    """
    return f"model/{model_id}/{model_name}.gguf"


def run_model_key(run_id: str, model_name: str = "model") -> str:
    """Return the S3 key for a model produced by a training run.

    Format: model/runs/{run_id}/{model_name}.gguf

    Finished models live under ``model/``, which no lifecycle rule expires.
    They must never go under ``workflow/``: that prefix holds short-lived run
    artefacts (checkpoints, logs) and is expired by a bucket lifecycle rule.
    """
    return f"model/runs/{run_id}/{model_name}.gguf"


def dataset_train_key(dataset_id: str) -> str:
    """Return the S3 key for a dataset's training split.

    Format: dataset/{dataset_id}/train.jsonl
    """
    return f"dataset/{dataset_id}/train.jsonl"


def dataset_eval_key(dataset_id: str) -> str:
    """Return the S3 key for a dataset's evaluation split.

    Format: dataset/{dataset_id}/eval.jsonl
    """
    return f"dataset/{dataset_id}/eval.jsonl"


def run_dataset_train_key(run_id: str) -> str:
    """Return the S3 key for the training split generated by a training run.

    Format: dataset/runs/{run_id}/train.jsonl

    Generated datasets are kept under ``dataset/`` so they outlive the run's
    short-lived ``workflow/`` artefacts and can be reused for retraining.
    """
    return dataset_train_key(f"runs/{run_id}")


def run_dataset_eval_key(run_id: str) -> str:
    """Return the S3 key for the evaluation split generated by a training run.

    Format: dataset/runs/{run_id}/eval.jsonl
    """
    return dataset_eval_key(f"runs/{run_id}")
